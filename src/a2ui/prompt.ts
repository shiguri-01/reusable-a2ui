export function buildUserTurnPrompt(options: {
  userText: string;
  activeVersionName: string;
  currentMessagesJson: string;
}): string {
  return [
    `今日の日付: ${getTodayIso()}`,
    `現在使用中の UI バージョン: ${options.activeVersionName}`,
    "現在のダッシュボード A2UI JSON:",
    "```json",
    options.currentMessagesJson,
    "```",
    "",
    "ユーザーからの依頼:",
    options.userText,
  ].join("\n");
}
